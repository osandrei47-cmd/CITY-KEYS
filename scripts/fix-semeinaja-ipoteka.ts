function text(t: string, format = 0) {
  return { mode: "normal", text: t, type: "text", style: "", detail: 0, format, version: 1 };
}

function paragraph(children: unknown[]) {
  return { type: "paragraph", format: "", indent: 0, version: 1, children, direction: null, textStyle: "", textFormat: 0 };
}

function p(t: string) {
  return paragraph([text(t)]);
}

function heading(t: string, tag: "h2" | "h3" = "h2") {
  return { tag, type: "heading", format: "", indent: 0, version: 1, children: [text(t)], direction: null };
}

function listItem(children: unknown[], value: number) {
  return { type: "listitem", value, format: "", indent: 0, version: 1, children, direction: null };
}

function bulletList(items: string[]) {
  return {
    tag: "ul",
    type: "list",
    start: 1,
    format: "",
    indent: 0,
    version: 1,
    children: items.map((t, i) => listItem([text(t)], i + 1)),
    listType: "bullet",
    direction: null,
  };
}

function link(url: string, label: string) {
  return {
    type: "link",
    fields: { url, newTab: false, linkType: "custom" },
    format: "",
    indent: 0,
    version: 3,
    children: [text(label)],
    direction: null,
  };
}

function hr() {
  return { type: "horizontalrule", version: 1 };
}

